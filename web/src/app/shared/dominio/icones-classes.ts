export function iconeDaClasse(nome: string): string | null {
  const chave = nome
    .normalize("NFD")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
  const id = Object.hasOwn(ICONES, chave) ? ICONES[chave] : undefined;
  return id === undefined ? null : `icones-classes/${id}.png`;
}
